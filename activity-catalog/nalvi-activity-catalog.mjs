export function getCatalogEntry(activityType) {
  return NALVI_ACTIVITY_CATALOG_V1.activities[String(activityType || "").trim()] || null;
}

export function isSupportedActivityType(activityType) {
  return Boolean(getCatalogEntry(activityType));
}

export function isEnabledActivityType(activityType) {
  return getCatalogEntry(activityType)?.enabled === true;
}

export function allowedTypesForError(errorType, { audioEnabled = ENABLE_AUDIO_INTERVENTIONS } = {}) {
  const type = String(errorType || "UNKNOWN_ERROR");
  if (type === "LISTENING_CONFUSION" && audioEnabled) {
    return [ACTIVITY_TYPES.AUDIO_SELECT, ACTIVITY_TYPES.AUDIO_MISSING_WORD, ACTIVITY_TYPES.AUDIO_TO_TILES];
  }
  return [...(ERROR_ACTIVITY_MATRIX[type] || ERROR_ACTIVITY_MATRIX.UNKNOWN_ERROR)].filter(isEnabledActivityType);
}

export function cognitiveDemandFor(activityType) {
  return getCatalogEntry(activityType)?.cognitiveDemand || null;
}

export function catalogAudit() {
  const entries = Object.entries(NALVI_ACTIVITY_CATALOG_V1.activities);
  return Object.freeze({
    version: NALVI_ACTIVITY_CATALOG_VERSION,
    enabledTypes: entries.filter(([, value]) => value.enabled).map(([key]) => key),
    disabledTypes: entries.filter(([, value]) => !value.enabled).map(([key]) => key),
    audioEnabled: ENABLE_AUDIO_INTERVENTIONS,
    morphemeBuilderEnabled: false,
    paso8cStarted: false
  });
}

